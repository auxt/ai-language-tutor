"""Merge tools/topics/*.txt into js/lang/*.js (the block between the "extra topics" markers).

Run from anywhere: python3 tools/build_topics.py [--write]. Russian transliteration is
generated (tools/ru_translit.py); Arabic transliteration is written by hand in the lists.

File format: first line '# <topic id> | <sk name> | es | de | fr | ar | ru' (topic names),
then '@A1' ... '@C1' headers and rows 'sk | es | de | fr | ar | ar_tr | ru'.
In sk, {acc} {po} {nom} {krajina} are replaced per language (Slovak forms).
"""
import json, re, sys, glob, os
from pathlib import Path
TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
sys.path.insert(0, str(TOOLS))
from ru_translit import translit
LANGS = ['es', 'de', 'fr', 'ar', 'ru']
SK = {
 'es': {'acc': 'španielčinu', 'po': 'po španielsky', 'nom': 'španielčina', 'krajina': 'Španielsku'},
 'de': {'acc': 'nemčinu', 'po': 'po nemecky', 'nom': 'nemčina', 'krajina': 'Nemecku'},
 'fr': {'acc': 'francúzštinu', 'po': 'po francúzsky', 'nom': 'francúzština', 'krajina': 'Francúzsku'},
 'ar': {'acc': 'arabčinu', 'po': 'po arabsky', 'nom': 'arabčina', 'krajina': 'Emirátoch'},
 'ru': {'acc': 'ruštinu', 'po': 'po rusky', 'nom': 'ruština', 'krajina': 'Rusku'},
}
ORDER = ['numbers', 'family', 'home', 'work', 'health', 'food', 'hobbies', 'weather', 'city', 'tech', 'feelings', 'emergency', 'social', 'school']
QUOTA = {'A1': 12, 'A2': 14, 'B1': 12, 'B2': 10, 'C1': 6}

def parse(path):
    topic, names, levels, level = None, None, {}, None
    for n, line in enumerate(open(path, encoding='utf-8'), 1):
        line = line.strip()
        if not line: continue
        if line.startswith('#'):
            parts = [p.strip() for p in line[1:].split('|')]
            assert len(parts) == 7, (path, n, 'header needs 7 fields')
            topic, names = parts[0], dict(zip(['sk'] + LANGS, parts[1:]))
            continue
        if line.startswith('@'):
            level = line[1:].strip(); levels[level] = []; continue
        f = [p.strip() for p in line.split('|')]
        assert len(f) == 7 and all(f), (path, n, len(f), line)
        sk, es, de, fr, ar, ar_tr, ru = f
        assert re.search('[؀-ۿ]', ar) and not re.search('[؀-ۿ]', ar_tr), (path, n, 'arabic fields')
        assert re.search('[а-яё]', ru.lower()), (path, n, 'russian')
        levels[level].append(dict(sk=sk, es=es, de=de, fr=fr, ar=ar, ar_tr=ar_tr, ru=ru, ru_tr=translit(ru)))
    return topic, names, levels

def load_all():
    out = {}
    for p in sorted(glob.glob(str(TOOLS / 'topics' / '*.txt'))):
        t, names, lv = parse(p); out[t] = (names, lv)
    return out

def report(data):
    seen = {}
    for t, (names, lv) in data.items():
        counts = {k: len(v) for k, v in lv.items()}
        print(f'{t:10} {sum(counts.values()):3}  {counts}' + ('' if counts == QUOTA else '  <- quota ' + str(QUOTA)))
        for k, rows in lv.items():
            for r in rows:
                if r['sk'] in seen: print('  DUP sk:', r['sk'], 'also in', seen[r['sk']])
                seen[r['sk']] = f'{t}/{k}'
    return seen

def write(data):
    for lid in LANGS:
        p = ROOT / 'js' / 'lang' / f'{lid}.js'
        s = open(p, encoding='utf-8').read()
        s = re.sub(r'\n  // >>> extra topics.*?// <<< extra topics <<<\n', '\n', s, flags=re.S)
        lines = ['  // >>> extra topics (generated by tools/build_topics.py from tools/topics/*.txt; edit those, not here) >>>',
                 '  extraTopics: ' + json.dumps({t: data[t][0][lid] for t in ORDER if t in data}, ensure_ascii=False) + ',',
                 '  extra: {']
        for level in QUOTA:
            lines.append(f'    {level}: {{')
            for t in ORDER:
                if t not in data or level not in data[t][1]: continue
                lines.append(f'      {t}: [')
                for r in data[t][1][level]:
                    sk = r['sk'].format(**SK[lid])
                    row = [r[lid], r[f'{lid}_tr'], sk] if lid in ('ar', 'ru') else [r[lid], sk]
                    lines.append('        ' + json.dumps(row, ensure_ascii=False) + ',')
                lines.append('      ],')
            lines.append('    },')
        lines += ['  },', '  // <<< extra topics <<<']
        assert s.endswith('};\n')
        s = s[:-3] + '\n'.join(lines) + '\n};\n'
        open(p, 'w', encoding='utf-8').write(s)

if __name__ == '__main__':
    data = load_all(); report(data)
    if '--write' in sys.argv: write(data); print('written')
