"""Merge tools/words/<lang>.txt into js/lang/<lang>.js (the block between the "words" markers).

Run from anywhere: python3 tools/build_words.py [--write]

Each list holds the 3,000 most frequent words of the language, most frequent first, as
counted in film and TV subtitles (FrequencyWords, OpenSubtitles 2018), lemmatised and
cleaned by hand: names, interjections and subtitle noise removed, a few everyday words
added at the end. The app gives each word a level from its rank (see phrases.js).

Line format (one word per line, "|" between fields, note optional):
    es, de, fr, ru:  word | Slovak meaning | note
    ar:              word | transliteration | Slovak meaning | note
Russian transliteration is generated (tools/ru_translit.py). The Slovak meaning is read
aloud, so keep it to what should be spoken; alternatives and usage go in the note.
"""
import json, re, sys
from pathlib import Path
TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
sys.path.insert(0, str(TOOLS))
from ru_translit import translit

LANGS = ['es', 'de', 'fr', 'ar', 'ru']
TOPIC_NAME = {'es': 'Vocabulario', 'de': 'Wortschatz', 'fr': 'Vocabulaire', 'ar': 'المفردات', 'ru': 'Словарный запас'}
COUNT = 3000


def parse(lid):
    rows, seen = [], {}
    for n, line in enumerate(open(TOOLS / 'words' / f'{lid}.txt', encoding='utf-8'), 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        f = [p.strip() for p in line.split('|')]
        want = (3, 4) if lid == 'ar' else (2, 3)
        assert len(f) in want and all(f), (lid, n, line)
        if lid == 'ar':
            word, tr, sk, note = (f + [''])[:4]
            assert re.search('[؀-ۿ]', word) and not re.search('[؀-ۿ]', tr), (lid, n, line)
        else:
            word, sk, note = (f + [''])[:3]
            tr = translit(word) if lid == 'ru' else ''
        if lid == 'ru':
            assert re.search('[а-яё]', word.lower()), (lid, n, line)
        assert word not in seen, (lid, n, 'duplicate of line', seen[word], word)
        seen[word] = n
        rows.append((word, tr, sk, note))
    assert len(rows) == COUNT, (lid, len(rows))
    return rows


def write(lid, rows):
    p = ROOT / 'js' / 'lang' / f'{lid}.js'
    s = open(p, encoding='utf-8').read()
    s = re.sub(r'\n  // >>> words.*?// <<< words <<<\n', '\n', s, flags=re.S)
    lines = ['  // >>> words (generated by tools/build_words.py from tools/words/*.txt; edit those, not here) >>>',
             f'  wordsTopic: {json.dumps(TOPIC_NAME[lid], ensure_ascii=False)},',
             '  words: [']
    for word, tr, sk, note in rows:
        row = [word, tr, sk] if lid in ('ar', 'ru') else [word, sk]
        if note:
            row.append(note)
        lines.append('    ' + json.dumps(row, ensure_ascii=False) + ',')
    lines += ['  ],', '  // <<< words <<<']
    assert s.endswith('};\n')
    s = s[:-3] + '\n'.join(lines) + '\n};\n'
    open(p, 'w', encoding='utf-8').write(s)


if __name__ == '__main__':
    for lid in LANGS:
        rows = parse(lid)
        print(f'{lid}: {len(rows)} words, {sum(1 for r in rows if r[3])} with a note')
        if '--write' in sys.argv:
            write(lid, rows)
    if '--write' in sys.argv:
        print('written')
